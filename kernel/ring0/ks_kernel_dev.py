def _find_tool(name: str, prefix: str = "") -> Optional[str]:
    """Find an LLVM tool, trying versioned names (clang-17, clang-16, …)"""
    candidates = []
    if prefix:
        candidates.append(os.path.join(prefix, name))
    # Prefer highest version
    for ver in range(20, 13, -1):
        candidates.append(f"{name}-{ver}")
    candidates.append(name)
    for c in candidates:
        path = shutil.which(c)
        if path:
            return path
    return None

def detect_llvm_tools(prefix: str = "") -> Dict[str, str]:
    """Return dict of discovered LLVM tool paths"""
    tools = {}
    for t in ("clang", "clang++", "opt", "llc", "lld", "ld.lld",
              "llvm-ar", "llvm-objcopy", "llvm-strip", "llvm-profdata"):
        path = _find_tool(t, prefix)
        if path:
            tools[t] = path
    return tools


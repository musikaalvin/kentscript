def install(dest: str = ".") -> None:
    d = Path(dest)
    d.mkdir(parents=True, exist_ok=True)

    kernel_dir = d / "minios"
    kernel_dir.mkdir(exist_ok=True)

    files = {
        "ks_kernel_dev.py":        __file__,  # self
        d / "gdt.c":               GDT_C,
        d / "idt.c":               IDT_C,
        d / "scheduler.c":         SCHEDULER_C,
        d / "vmem.c":              VMEM_C,
        d / "syscall_dispatch.c":  SYSCALL_C,
    }

    for path, content in files.items():
        if path == "ks_kernel_dev.py":
            continue
        Path(path).write_text(
            textwrap.dedent(content).lstrip(), encoding="utf-8"
        )
        print(f"  wrote {path}")

    print("\n[KernelDevMode] ✓ All kernel subsystem files installed.")

if __name__ == "__main__":
    import sys
    dest = sys.argv[1] if len(sys.argv) > 1 else "."
    install(dest)

class PGOWorkflow:
    """Two-pass PGO: instrument → run → merge → re-compile."""

    def __init__(self, tools: Dict[str, str]):
        self.tools = tools

    def instrument(self, src_path: str, inst_bin: str, config: LLVMConfig) -> bool:
        clang = self.tools.get("clang") or self.tools.get("clang++")
        if not clang:
            print("[PGO] clang not found"); return False
        cmd = [clang, f"-O{config.opt_level.value}",
               "-fprofile-generate", src_path, "-o", inst_bin]
        cmd += config.extra_clang
        rc, _, err = subprocess.run(cmd, capture_output=True, text=True,
                                    stdout=subprocess.PIPE, stderr=subprocess.PIPE), 0, ""
        if isinstance(rc, subprocess.CompletedProcess):
            rc, _, err = rc.returncode, rc.stdout, rc.stderr
        return rc == 0

    def merge_profiles(self, raw_dir: str, out_profdata: str) -> bool:
        llvm_profdata = self.tools.get("llvm-profdata")
        if not llvm_profdata:
            print("[PGO] llvm-profdata not found"); return False
        raw_files = list(Path(raw_dir).glob("*.profraw"))
        if not raw_files:
            print("[PGO] No .profraw files found"); return False
        cmd = [llvm_profdata, "merge", "-output", out_profdata] + [str(f) for f in raw_files]
        return subprocess.run(cmd).returncode == 0

    def compile_with_profile(self, src_path: str, out_path: str,
                             profdata: str, config: LLVMConfig) -> bool:
        clang = self.tools.get("clang") or self.tools.get("clang++")
        if not clang: return False
        cfg2 = LLVMConfig(**{**config.__dict__, "enable_pgo": True, "pgo_profile": profdata})
        pipeline = LLVMOptPipeline(self.tools, cfg2)
        # For simplicity: compile directly with clang -fprofile-use
        cmd = [clang, f"-O{config.opt_level.value}",
               f"-fprofile-use={profdata}", src_path, "-o", out_path]
        cmd += config.extra_clang
        return subprocess.run(cmd).returncode == 0


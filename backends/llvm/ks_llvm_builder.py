from __future__ import annotations
import os, sys, subprocess, shutil, tempfile, platform, json, textwrap
from pathlib import Path
from dataclasses import dataclass, field
from typing import List, Optional, Dict, Tuple
from enum import Enum

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

class LLVMOptLevel(Enum):
    NONE  = "0"
    LESS  = "1"
    STD   = "2"
    AGGR  = "3"
    SIZE  = "s"
    SIZES = "z"

@dataclass
class LLVMConfig:
    """Full LLVM pipeline configuration"""
    opt_level:     LLVMOptLevel = LLVMOptLevel.AGGR
    enable_lto:    bool  = True      # Link-Time Optimisation
    enable_pgo:    bool  = False     # Profile-Guided (needs profile data)
    pgo_profile:   str   = ""        # Path to .profdata
    enable_vec:    bool  = True      # Auto-vectorisation
    enable_slp:    bool  = True      # SLP vectoriser
    target_cpu:    str   = "native"  # or "x86-64-v3", "cortex-a72", …
    target_triple: str   = ""        # auto-detected if empty
    extra_clang:   List[str] = field(default_factory=list)
    extra_opt:     List[str] = field(default_factory=list)
    extra_link:    List[str] = field(default_factory=list)
    llvm_prefix:   str   = ""        # /usr/lib/llvm-16/bin etc; auto-detected

# ---------------------------------------------------------------------------
# Tool Detection
# ---------------------------------------------------------------------------

def _find_tool(name: str, prefix: str = "") -> Optional[str]:
    """Find an LLVM tool, trying versioned names (clang-17, clang-16, …)"""
    candidates = []
    if prefix:
        candidates.append(os.path.join(prefix, name))
    # Prefer highest version
    for ver in range(20, 13, -1):
        candidates.append(f"{name}-{ver}")
    candidates.append(name)
    for c in candidates:
        path = shutil.which(c)
        if path:
            return path
    return None

def detect_llvm_tools(prefix: str = "") -> Dict[str, str]:
    """Return dict of discovered LLVM tool paths"""
    tools = {}
    for t in ("clang", "clang++", "opt", "llc", "lld", "ld.lld",
              "llvm-ar", "llvm-objcopy", "llvm-strip", "llvm-profdata"):
        path = _find_tool(t, prefix)
        if path:
            tools[t] = path
    return tools


LLVM_CMAKE_OPTS = [
    "-DCMAKE_BUILD_TYPE=Release",
    "-DLLVM_ENABLE_PROJECTS=clang;lld",
    "-DLLVM_ENABLE_RUNTIMES=compiler-rt",
    "-DLLVM_TARGETS_TO_BUILD=X86;AArch64;RISCV",
    "-DLLVM_ENABLE_ASSERTIONS=OFF",
    "-DLLVM_ENABLE_LTO=Thin",
    "-DLLVM_ENABLE_ZLIB=ON",
    "-DLLVM_BUILD_LLVM_DYLIB=ON",
    "-DLLVM_LINK_LLVM_DYLIB=ON",
    "-DLLVM_ENABLE_LIBCXX=OFF",
    "-DLLVM_PARALLEL_LINK_JOBS=2",
    "-DCLANG_ENABLE_ARCMT=OFF",
    "-DCLANG_ENABLE_STATIC_ANALYZER=OFF",
]

def build_llvm_from_source(src_dir: str, build_dir: str,
                            install_dir: str, jobs: int = 0) -> bool:
    """
    Run cmake + ninja to build LLVM from source.
    src_dir   = path to llvm-project/llvm (cloned from github)
    build_dir = cmake build directory
    install_dir = prefix for install
    """
    if jobs <= 0:
        import multiprocessing
        jobs = multiprocessing.cpu_count()

    cmake = shutil.which("cmake")
    ninja = shutil.which("ninja") or shutil.which("ninja-build")
    if not cmake:
        print("[LLVM-SRC] cmake not found — cannot build LLVM from source"); return False
    if not ninja:
        print("[LLVM-SRC] ninja not found — install ninja-build"); return False

    Path(build_dir).mkdir(parents=True, exist_ok=True)

    cmake_cmd = [cmake,
                 "-G", "Ninja",
                 f"-DCMAKE_INSTALL_PREFIX={install_dir}",
                 *LLVM_CMAKE_OPTS,
                 src_dir]
    print("[LLVM-SRC] Running cmake …")
    rc = subprocess.run(cmake_cmd, cwd=build_dir).returncode
    if rc != 0: return False

    print(f"[LLVM-SRC] Building with {jobs} jobs …")
    rc = subprocess.run([ninja, "-j", str(jobs)], cwd=build_dir).returncode
    if rc != 0: return False

    print("[LLVM-SRC] Installing …")
    rc = subprocess.run([ninja, "install"], cwd=build_dir).returncode
    if rc != 0: return False

    print(f"[LLVM-SRC] ✓ LLVM installed to {install_dir}")
    return True

# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def get_pipeline(config: Optional[LLVMConfig] = None) -> Optional[LLVMOptPipeline]:
    """Quick factory — detect tools, return pipeline. Returns None if no LLVM found."""
    if config is None:
        config = LLVMConfig()
    tools = detect_llvm_tools(config.llvm_prefix)
    if not tools:
        return None
    return LLVMOptPipeline(tools, config)

def compile_ks_to_native(ir_path: str, out_path: str,
                          config: Optional[LLVMConfig] = None) -> bool:
    """One-shot: .ll IR → optimised native binary."""
    pipeline = get_pipeline(config)
    if pipeline is None:
        print("[LLVM] No LLVM tools found. Install clang+lld or set llvm_prefix.")
        return False
    return pipeline.compile(ir_path, out_path)

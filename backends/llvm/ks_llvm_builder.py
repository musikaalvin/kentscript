class LLVMIREmitter:
    """
    Wraps the existing KentScript LLVM backend and adds optimisation
    metadata attributes (nounwind, willreturn, nosync, mustprogress).
    """

    def __init__(self, backend=None):
        self._backend = backend  # existing LLVMBackend instance

    def emit_ir(self, ast, config: LLVMConfig, out_path: str) -> str:
        """
        Generate LLVM IR from AST, annotated for aggressive optimisation.
        Returns path to .ll file.
        """
        if self._backend is not None:
            ir_text = self._backend.generate(ast)
        else:
            # Minimal stub IR for testing the pipeline
            ir_text = textwrap.dedent("""                ; Generated by KentScript LLVM IR Emitter
                target datalayout = "e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-f80:128-n8:16:32:64-S128"
                target triple = "x86_64-unknown-linux-gnu"

                define i64 @ks_main() #0 {
                entry:
                  ret i64 0
                }

                attributes #0 = { nounwind willreturn nosync mustprogress }
            """)

        # Inject target CPU attribute
        cpu_attr = 'mustprogress nounwind willreturn nosync "target-cpu"="{cpu}"'.format(cpu=config.target_cpu)
        ir_text = ir_text.replace(
            "attributes #0 = { nounwind willreturn nosync mustprogress }",
            f"attributes #0 = {{ {cpu_attr} }}"
        )

        Path(out_path).write_text(ir_text, encoding="utf-8")
        return out_path

# ---------------------------------------------------------------------------
# Optimisation Pipeline
# ---------------------------------------------------------------------------

class LLVMOptPipeline:
    """
    Runs:  .ll → opt (O3 + vectorise + LTO prep) → .bc
    Then:  .bc → llc (native object) → ld.lld (final ELF/binary)
    """

    def __init__(self, tools: Dict[str, str], config: LLVMConfig):
        self.tools  = tools
        self.config = config

    def _run(self, cmd: List[str], *, cwd: Optional[str] = None, capture: bool = False) -> Tuple[int, str, str]:
        result = subprocess.run(cmd, cwd=cwd, capture_output=capture, text=True)
        return result.returncode, result.stdout or "", result.stderr or ""

    # -- Step 1: opt ---------------------------------------------------------
    def optimise_ir(self, ir_path: str, bc_path: str) -> bool:
        """Run 'opt' on IR file, produce optimised bitcode."""
        opt = self.tools.get("opt")
        if not opt:
            print("[LLVM] 'opt' not found — skipping IR optimisation pass")
            # copy as-is for llc
            shutil.copy(ir_path, bc_path)
            return True

        cmd = [opt,
               f"-O{self.config.opt_level.value}",
               "--passes=default<O3>"]

        if self.config.enable_vec:
            cmd += ["--vectorize-loops", "--loop-vectorize", "--slp-vectorize"]
        if self.config.enable_lto:
            cmd += ["--lto-newpm-passes=default<O3>"]
        if self.config.enable_pgo and self.config.pgo_profile:
            cmd += [f"--pgo-instrument-path={self.config.pgo_profile}"]

        cmd += self.config.extra_opt
        cmd += ["-o", bc_path, ir_path]

        rc, out, err = self._run(cmd, capture=True)
        if rc != 0:
            print(f"[LLVM][opt] ERROR:\n{err}")
            return False
        return True

    # -- Step 2: llc ---------------------------------------------------------
    def compile_to_object(self, bc_path: str, obj_path: str) -> bool:
        """Run 'llc' to lower bitcode → native object."""
        llc = self.tools.get("llc")
        if not llc:
            print("[LLVM] 'llc' not found — cannot emit native object")
            return False

        cmd = [llc,
               f"-O{self.config.opt_level.value}",
               f"--mcpu={self.config.target_cpu}",
               "--filetype=obj"]

        if self.config.enable_vec:
            cmd += ["--vectorize-loops"]

        if self.config.target_triple:
            cmd += [f"--mtriple={self.config.target_triple}"]

        cmd += ["-o", obj_path, bc_path]

        rc, out, err = self._run(cmd, capture=True)
        if rc != 0:
            print(f"[LLVM][llc] ERROR:\n{err}")
            return False
        return True

    # -- Step 3: LTO link via lld -------------------------------------------
    def link(self, obj_paths: List[str], out_path: str,
             extra_libs: Optional[List[str]] = None) -> bool:
        """Link object files with ld.lld (supports ThinLTO)."""
        lld = self.tools.get("ld.lld") or self.tools.get("lld")
        if not lld:
            print("[LLVM] 'ld.lld' not found — falling back to system linker")
            lld = shutil.which("ld") or "ld"

        cmd = [lld, "--eh-frame-hdr"]

        if self.config.enable_lto:
            cmd += ["--lto-O3", "--thinlto-jobs=all"]

        cmd += obj_paths
        cmd += (extra_libs or [])
        cmd += self.config.extra_link
        cmd += ["-o", out_path]

        rc, out, err = self._run(cmd, capture=True)
        if rc != 0:
            print(f"[LLVM][lld] ERROR:\n{err}")
            return False
        return True

    # -- Full pipeline -------------------------------------------------------
    def compile(self, ir_path: str, out_path: str,
                extra_objs: Optional[List[str]] = None,
                extra_libs: Optional[List[str]] = None) -> bool:
        """ir_path (.ll) → optimised native binary at out_path."""
        with tempfile.TemporaryDirectory(prefix="ks_llvm_") as tmp:
            bc_path  = os.path.join(tmp, "prog.bc")
            obj_path = os.path.join(tmp, "prog.o")

            print(f"[LLVM] Optimising IR  ({self.config.opt_level.name}) …")
            if not self.optimise_ir(ir_path, bc_path):  return False

            print("[LLVM] Lowering to native object …")
            if not self.compile_to_object(bc_path, obj_path): return False

            objs = [obj_path] + (extra_objs or [])
            print(f"[LLVM] Linking → {out_path} …")
            if not self.link(objs, out_path, extra_libs): return False

        print(f"[LLVM] ✓ Binary ready: {out_path}")
        return True


        self.code.append('/* Type checking enforced at compile-time by GCC/Clang */')
        self.code.append('/* No implicit conversions - No silent fallthrough - Deterministic output */')
        self.code.append('')
        self.code.append('#include "ks_typesystem.h"')
        self.code.append('#include <stdio.h>')
        self.code.append('#include <stdlib.h>')
        self.code.append('#include <string.h>')
        self.code.append('#include <stdint.h>')
        self.code.append('#include <stdbool.h>')
        self.code.append('')
        self.code.append('/* STRICT MODE: All conversions explicit, all returns checked */')
        self.code.append('')
        
        # Dict helper functions

        self.code.append('')
        
        # Set helper functions
        self.code.append('/* Set hash table */')
        self.code.append('typedef struct _ks_set_node {')
        self.code.append('    long long val;')
        self.code.append('    struct _ks_set_node* next;')
        self.code.append('} _ks_set_node;')
        self.code.append('typedef struct { _ks_set_node* buckets[32]; } _ks_set;')
        self.code.append('')
        self.code.append('static unsigned int _ks_hash_int(long long v) {')
        self.code.append('    return (unsigned int)(v % 32);')
        self.code.append('}')
        self.code.append('')
        self.code.append('static _ks_set* _ks_set_new(void) {')
